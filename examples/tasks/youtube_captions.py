"""Read the uploader-provided caption track. Running this script consumes FlashData credits."""

from langchain_flashdata import FlashDataYouTubeCaptions

tool = FlashDataYouTubeCaptions()
arguments = {"video_id": "dQw4w9WgXcQ", "language": "en", "auto": False}
result = tool.invoke(arguments)
item = result["results"][0]
print(item.get("languageCode"), item.get("isAutoGenerated"))
for segment in item.get("segments", []):
    print(segment["start"], segment["end"], segment["text"])
